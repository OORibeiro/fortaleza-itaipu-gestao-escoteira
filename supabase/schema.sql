create table if not exists public.financial_transactions (
  id bigint generated by default as identity primary key,
  description text not null,
  category text not null,
  counterparty text not null default '',
  kind text not null check (kind in ('income', 'expense')),
  amount_cents integer not null check (amount_cents > 0),
  occurred_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_financial_transactions_occurred_at
  on public.financial_transactions (occurred_at desc);

create index if not exists idx_financial_transactions_kind_occurred_at
  on public.financial_transactions (kind, occurred_at desc);

create table if not exists public.monthly_dues (
  id bigint generated by default as identity primary key,
  member_name text not null,
  patrol text not null,
  reference_month text not null,
  amount_cents integer not null check (amount_cents > 0),
  status text not null check (status in ('paid', 'overdue', 'pending')),
  due_date date not null,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_monthly_dues_reference_status
  on public.monthly_dues (reference_month, status);

